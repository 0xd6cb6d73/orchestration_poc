"""Reproduce/export public evidence and validate the sandbox without model calls."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

from poc.evaluation.authorization.grading import grade_authorization
from poc.evaluation.suite.models import Answer, TaskCase
from poc.evaluation.suite.tasks import generate


def export_case(case: TaskCase, output: Path, include_reference: bool = False) -> dict[str, Any]:
    """Exclusive output directory; public tables and optional operator references are separated."""
    output.mkdir(parents=True, exist_ok=False)
    public = output / "public"
    public.mkdir()
    (public / "task.txt").write_text(case.input.prompt, encoding="utf-8")
    files: dict[str, Any] = {}
    for name, rows in case.input.tables.items():
        path = public / f"{name}.jsonl"
        digest = hashlib.sha256()
        size = 0
        with path.open("wb") as stream:
            for row in rows:
                data = (json.dumps(row, sort_keys=True, separators=(",", ":")) + "\n").encode()
                stream.write(data)
                digest.update(data)
                size += len(data)
        files[name] = {
            "path": f"public/{path.name}",
            "rows": len(rows),
            "bytes": size,
            "sha256": digest.hexdigest(),
            "columns": list(rows[0]),
        }
    manifest = {
        "case_id": case.id,
        "generator_version": case.version,
        "seed": case.seed,
        "split": case.split,
        "difficulty": case.difficulty,
        "provenance": "Synthetic data generated by poc.evaluation.authorization; no external corpus or personal data.",
        "prompt_sha256": hashlib.sha256(case.input.prompt.encode()).hexdigest(),
        "tables": files,
        "total_table_bytes": sum(f["bytes"] for f in files.values()),
        "operator_reference_included": include_reference,
    }
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    if include_reference:
        private = output / "private"
        private.mkdir()
        (private / "reference.json").write_text(json.dumps(case.expected) + "\n", encoding="utf-8")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("generate", "check", "grade"))
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--split", choices=("dev", "test"), default="dev")
    parser.add_argument("--difficulty", choices=("standard", "hard", "stress"), default="standard")
    parser.add_argument("--output", type=Path, help="New directory, preferably under ignored var/")
    parser.add_argument(
        "--include-reference", action="store_true", help="Export operator-only gold under private/"
    )
    parser.add_argument("--answer", type=Path, help='JSON file containing {"values": {...}}')
    args = parser.parse_args()
    if args.command == "generate" and args.output is None:
        parser.error("generate requires --output")
    if args.command == "grade" and args.answer is None:
        parser.error("grade requires --answer")
    if args.command != "generate" and (args.output or args.include_reference):
        parser.error("--output and --include-reference are only for generate")
    if args.command != "grade" and args.answer:
        parser.error("--answer is only for grade")
    case = generate("authorization", args.seed, args.split, args.difficulty)
    if args.command == "generate":
        try:
            manifest = export_case(case, args.output, args.include_reference)
        except FileExistsError:
            parser.error("output already exists; choose a new directory")
        print(json.dumps(manifest, indent=2))
    elif args.command == "check":
        witness = Answer(values=case.expected["submission"])
        scores = grade_authorization(case, witness)
        deployed = witness.model_copy(deep=True)
        deployed.values["changes"] = []
        baseline = grade_authorization(case, deployed)
        print(
            json.dumps(
                {
                    "case_id": case.id,
                    "witness": scores,
                    "unrepaired": baseline,
                    "hidden_replays": len(case.expected["checks"]),
                    "note": "Environment/grader self-check only; no agent solved this task.",
                },
                indent=2,
            )
        )
        if scores["exact"] != 1 or baseline["exact"] != 0:
            raise SystemExit(1)
    else:
        answer = Answer.model_validate_json(args.answer.read_text(encoding="utf-8"))
        print(json.dumps(grade_authorization(case, answer), indent=2))


if __name__ == "__main__":
    main()
